/**
 * Tests for the KSP-generated navigation extension accessor produced by `@ToOneAggregate`.
 *
 * Verifies that the accessor-driven ref delegate stored on the entity resolves the referenced
 * entity, propagates mutations via bubble-up, and cascades deletions — all through the generated
 * extension accessor rather than a hand-written companion val.
 */
internal class ToOneAggregateExtAccessorTest : StringSpec({

    reactiveScope()

    lateinit var ctx: LirpContext

    beforeEach {
        ctx = LirpContext()
    }

    afterEach {
        ctx.close()
    }

    "TestAlbumEntry.catalog resolves referenced TestArtistCatalog after entity is added to repository" {
        val catalogRepo = TestArtistCatalogRepo(ctx)
        val albumRepo = TestAlbumEntryRepo(ctx)

        val catalog = TestArtistCatalog(1, "ECM Records")
        catalogRepo.add(catalog)

        val album = TestAlbumEntry(100, "Köln Concert", catalogId = 1)
        albumRepo.add(album)

        val ref = album.catalog
        ref.referenceId shouldBe 1
        val resolved = ref.resolve()
        resolved.shouldBePresent()
        resolved.get().label shouldBe "ECM Records"
    }

    "TestAlbumEntry.catalog referenceId matches the stored scalar" {
        val catalogRepo = TestArtistCatalogRepo(ctx)
        val albumRepo = TestAlbumEntryRepo(ctx)

        val catalog = TestArtistCatalog(2, "Blue Note")
        catalogRepo.add(catalog)

        val album = TestAlbumEntry(200, "Kind of Blue", catalogId = 2)
        albumRepo.add(album)

        album.catalog.referenceId shouldBe album.catalogId
    }

    "TestAlbumEntry.catalog resolves Optional.empty when FK scalar is null" {
        val catalogRepo = TestArtistCatalogRepo(ctx)
        val albumRepo = TestAlbumEntryRepo(ctx)

        val album = TestAlbumEntry(300, "Unknown Album", catalogId = null)
        albumRepo.add(album)

        album.catalog.resolve().shouldNotBePresent()
    }

    "TestBubbleAlbum.catalog bubbleUp=true propagates TestArtistCatalog mutation to album subscriber" {
        val catalogRepo = TestArtistCatalogRepo(ctx)
        val albumRepo = TestBubbleAlbumRepo(ctx)

        val catalog = TestArtistCatalog(10, "Verve")
        catalogRepo.add(catalog)

        val album = TestBubbleAlbum(1000, "Getz/Gilberto", catalogId = 10)
        albumRepo.add(album)

        val receivedEvent = AtomicReference<AggregateMutationEvent<*, *>>(null)
        val latch = CountDownLatch(1)

        album.subscribeAsync { event ->
            if (event is AggregateMutationEvent<*, *>) {
                receivedEvent.set(event)
                latch.countDown()
            }
        }

        catalog.label = "Verve Records"

        latch.await(2, TimeUnit.SECONDS) shouldBe true
        receivedEvent.get().refName shouldBe "catalog"
    }

    "TestCascadeAlbum CASCADE deletion removes the referenced TestArtistCatalog" {
        val catalogRepo = TestArtistCatalogRepo(ctx)
        val cascadeAlbumRepo = TestCascadeAlbumRepo(ctx)

        val catalog = TestArtistCatalog(20, "Deutsche Grammophon")
        catalogRepo.add(catalog)

        val album = TestCascadeAlbum(2000, "Beethoven Sonatas", catalogId = 20)
        cascadeAlbumRepo.add(album)

        cascadeAlbumRepo.remove(album)

        catalogRepo.findById(20).shouldNotBePresent()
        cascadeAlbumRepo.findById(2000).shouldNotBePresent()
    }

    "TestAlbumEntry.catalog DETACH removal leaves referenced TestArtistCatalog intact" {
        val catalogRepo = TestArtistCatalogRepo(ctx)
        val albumRepo = TestAlbumEntryRepo(ctx)

        val catalog = TestArtistCatalog(30, "Columbia")
        catalogRepo.add(catalog)

        val album = TestAlbumEntry(3000, "Bridge Over Troubled Water", catalogId = 30)
        albumRepo.add(album)

        albumRepo.remove(album)

        catalogRepo.findById(30).shouldBePresent()
        albumRepo.findById(3000).shouldNotBePresent()
    }

    "TestAlbumEntry.catalog accessor throws IllegalStateException when entity is not in a repository" {
        val album = TestAlbumEntry(400, "Orphaned", catalogId = 5)

        shouldThrow<IllegalStateException> { album.catalog }
            .message shouldContain "Ensure the entity is added to its repository"
    }

    "TestRestrictAlbum RESTRICT delete does not throw when another album has a null optional FK scalar" {
        val catalogRepo = TestArtistCatalogRepo(ctx)
        val restrictAlbumRepo = TestRestrictAlbumRepo(ctx)

        val catalog = TestArtistCatalog(50, "Nonesuch Records")
        catalogRepo.add(catalog)

        // album1 references the catalog; album2 has a null FK (references nothing)
        val album1 = TestRestrictAlbum(5000, "Nonesuch Album", catalogId = 50)
        val album2 = TestRestrictAlbum(5001, "Unlinked Album", catalogId = null)
        restrictAlbumRepo.add(album1)
        restrictAlbumRepo.add(album2)

        // Removing album1 must not throw: album2 has a null FK so it does not reference the catalog
        shouldNotThrowAny { restrictAlbumRepo.remove(album1) }

        catalogRepo.findById(50).shouldBePresent()
        restrictAlbumRepo.findById(5000).shouldNotBePresent()
        restrictAlbumRepo.findById(5001).shouldBePresent()
    }

    "TestRestrictAlbum RESTRICT delete throws when another album with non-null FK still references the catalog" {
        val catalogRepo = TestArtistCatalogRepo(ctx)
        val restrictAlbumRepo = TestRestrictAlbumRepo(ctx)

        val catalog = TestArtistCatalog(60, "ECM Records")
        catalogRepo.add(catalog)

        val album1 = TestRestrictAlbum(6000, "ECM Album A", catalogId = 60)
        val album2 = TestRestrictAlbum(6001, "ECM Album B", catalogId = 60)
        restrictAlbumRepo.add(album1)
        restrictAlbumRepo.add(album2)

        // Both albums reference the same catalog — removing album1 is blocked by album2
        val ex = shouldThrow<IllegalStateException> { restrictAlbumRepo.remove(album1) }
        ex.message shouldContain "Cannot cascade-delete"
    }

    "TestRestrictAlbum close() on entity with null FK does not throw" {
        val restrictAlbumRepo = TestRestrictAlbumRepo(ctx)

        val album = TestRestrictAlbum(7000, "Unlinked Album", catalogId = null)
        restrictAlbumRepo.add(album)

        // Close must not throw even though the FK scalar is null
        shouldNotThrowAny { album.close() }
    }

    "TestAlbumEntry close() before being added to a repository does not allocate to-one ref delegates" {
        // Regression for WR-01: cancelAllBubbleUp must not call getOrComputeToOneRef (which
        // allocates and stores a delegate) when no delegate exists yet.
        val album = TestAlbumEntry(8000, "Never-added Album", catalogId = 42)

        // Close before adding to any repository — must not throw and must not create a delegate
        shouldNotThrowAny { album.close() }
        // After close, getToOneRef must still throw (no delegate was created during teardown)
        shouldThrow<IllegalStateException> { album.catalog }
            .message shouldContain "Ensure the entity is added to its repository"
    }
})