/**
 * Referenced catalog entity. A minimal music-domain entity used as a FK target
 * to verify `@ToOneAggregate` accessor navigation.
 */
@PersistenceMapping(name = "test_artist_catalog")
class TestArtistCatalog(override val id: Int, label: String) : ReactiveEntityBase<Int, TestArtistCatalog>() {
    var label: String by reactiveProperty(label)

    override val uniqueId: String get() = "test-artist-catalog-$id"

    override fun clone(): TestArtistCatalog = TestArtistCatalog(id, label)
}

/**
 * Owning entity carrying an optional FK scalar to [TestArtistCatalog] via `@ToOneAggregate`.
 * The accessor `testAlbumEntry.catalog` is generated by KSP into `TestAlbumEntry_LirpToOneExtAccessor.kt`.
 */
@PersistenceMapping(name = "test_album_entry")
class TestAlbumEntry(override val id: Int, title: String, catalogId: Int? = null) :
    ReactiveEntityBase<Int, TestAlbumEntry>() {
    var title: String by reactiveProperty(title)

    @ToOneAggregate(target = TestArtistCatalog::class, onDelete = CascadeAction.DETACH)
    var catalogId: Int? by reactiveProperty(catalogId)

    override val uniqueId: String get() = "test-album-entry-$id"

    override fun clone(): TestAlbumEntry = TestAlbumEntry(id, title, catalogId)
}

/**
 * Owning entity with a required FK scalar and `bubbleUp = true` to [TestArtistCatalog].
 *
 * `onDelete = NONE` suppresses the FK constraint check — a non-nullable FK scalar cannot use DETACH
 * (which would require nulling the column on delete). The test verifies bubble-up propagation only.
 */
@PersistenceMapping(name = "test_bubble_album")
class TestBubbleAlbum(override val id: Int, title: String, catalogId: Int) :
    ReactiveEntityBase<Int, TestBubbleAlbum>() {
    var title: String by reactiveProperty(title)

    @ToOneAggregate(target = TestArtistCatalog::class, bubbleUp = true, onDelete = CascadeAction.NONE)
    var catalogId: Int by reactiveProperty(catalogId)

    override val uniqueId: String get() = "test-bubble-album-$id"

    override fun clone(): TestBubbleAlbum = TestBubbleAlbum(id, title, catalogId)
}

